/** Tiny DOM helpers. User data always travels via textContent, never HTML. */

type Attrs = Record<string, string | number | boolean | null | undefined>;

export function el<T extends keyof HTMLElementTagNameMap>(
  tag: T,
  attrs: Attrs = {},
  ...children: Array<string | Node | null | false | undefined>
): HTMLElementTagNameMap[T] {
  const node = document.createElement(tag);
  for (const [key, value] of Object.entries(attrs)) {
    if (value === null || value === undefined || value === false) continue;
    if (key === 'class') node.className = String(value);
    else if (key.startsWith('data-') || key.startsWith('aria-')) node.setAttribute(key, String(value));
    else if (key in node && typeof value !== 'string') {
      (node as unknown as Record<string, unknown>)[key] = value;
    } else {
      node.setAttribute(key, String(value));
    }
  }
  for (const child of children) {
    if (child === null || child === false || child === undefined) continue;
    node.append(child instanceof Node ? child : document.createTextNode(child));
  }
  return node;
}

export function on<T extends EventTarget>(
  target: T,
  type: string,
  handler: (event: Event) => void,
  options?: AddEventListenerOptions,
): T {
  target.addEventListener(type, handler as EventListener, options);
  return target;
}

export function clear(node: Element | Document | DocumentFragment): void {
  node.replaceChildren();
}

/** Trigger a file download for locally generated bytes. Nothing is uploaded. */
export function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.append(link);
  link.click();
  link.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 5000);
}

export function button(
  label: string,
  attrs: Attrs & { kind?: 'primary' | 'plain' | 'danger' | 'quiet' } = {},
): HTMLButtonElement {
  const { kind, ...rest } = attrs;
  return el('button', { type: 'button', class: `btn${kind && kind !== 'plain' ? ` btn-${kind}` : ''}`, ...rest }, label);
}
